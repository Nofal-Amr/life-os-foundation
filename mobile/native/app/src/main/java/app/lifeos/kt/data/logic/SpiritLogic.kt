@Serializable
data class Zikr(val id: String, val title: String, val text: String? = null, val morning: String? = null, val evening: String? = null, val count: Int, val source: String? = null)

@Serializable
data class AzkarData(val azkar: List<Zikr>, val tasbihPhrases: List<String>, val tasbihTargets: List<Int>)

/** Parses assets/azkar.json, generated byte for byte from the website by tools/azkar-export.cjs. */
fun parseAzkar(json: String): AzkarData = Json { ignoreUnknownKeys = true }.decodeFromString(AzkarData.serializer(), json)

/** The azkar for one time of day, with that time's wording. */
fun azkarFor(data: AzkarData, time: String): List<Pair<Zikr, String>> = data.azkar.mapNotNull { zikr ->
    (zikr.text ?: if (time == "morning") zikr.morning else zikr.evening)?.let { zikr to it }
}

/** Morning from Fajr until Dhuhr, evening for the rest of the day (the web's azkarTimeAt). */
fun azkarTimeAt(now: Date, fajr: Date?, dhuhr: Date?): String {
    if (fajr == null || dhuhr == null) {
        val hour = java.util.Calendar.getInstance().apply { time = now }.get(java.util.Calendar.HOUR_OF_DAY)
        return if (hour in 4..11) "morning" else "evening"
    }
    return if (!now.before(fajr) && now.before(dhuhr)) "morning" else "evening"
}

fun azkarDone(logs: List<DhikrLog>, date: String, time: String) = logs.any { it.logDate == date && it.kind == time }

fun tasbihOn(logs: List<DhikrLog>, date: String) = logs.filter { it.logDate == date && it.kind == "tasbih" }.sumOf { it.count }

