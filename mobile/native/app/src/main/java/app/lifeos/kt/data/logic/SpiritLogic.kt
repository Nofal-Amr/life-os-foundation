/** The web's prayerCounts: a log counts as prayed unless it says missed (older rows: completed). */
fun prayed(log: PrayerLog): Boolean = log.status?.let { it != "missed" } ?: log.completed

/** Of the five on [date], how many were prayed. */
fun prayedOn(logs: List<PrayerLog>, date: String): Int {
    val five = PRAYERS.map { it.first }.toSet()
    return logs.filter { it.prayerDate == date && it.prayerName in five && prayed(it) }.map { it.prayerName }.toSet().size
}

/** Of the 35 over the seven days ending [date]. */
fun prayedInWeek(logs: List<PrayerLog>, date: LocalDate): Int = (0L..6L).sumOf { prayedOn(logs, date.minusDays(it).toString()) }

/** How the five were logged between two dates: a count per status and the total logged. Sunnah aren't counted. */
fun prayerStatusCounts(logs: List<PrayerLog>, from: String, to: String): Pair<Map<String, Int>, Int> {
    val five = PRAYERS.map { it.first }.toSet()
    val statuses = logs.filter { it.prayerDate in from..to && it.prayerName in five }.mapNotNull { prayerStatus(it) }
    return PRAYER_STATUSES.associate { (status, _) -> status to statuses.count { it == status } } to statuses.size
}

