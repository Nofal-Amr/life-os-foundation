const val KAABA_LAT = 21.422487
const val KAABA_LON = 39.826206

private fun rad(d: Double) = Math.toRadians(d)

fun normalise(degrees: Double) = ((degrees % 360) + 360) % 360

/** Great-circle bearing to the Kaaba, clockwise from true north. */
fun qiblaBearing(latitude: Double, longitude: Double): Double {
    val phi = rad(latitude)
    val dLambda = rad(KAABA_LON - longitude)
    val y = sin(dLambda)
    val x = cos(phi) * tan(rad(KAABA_LAT)) - sin(phi) * cos(dLambda)
    return normalise(Math.toDegrees(atan2(y, x)))
}

/** Distance to the Kaaba in km (haversine). */
fun distanceToKaabaKm(latitude: Double, longitude: Double): Double {
    val dPhi = rad(KAABA_LAT - latitude)
    val dLambda = rad(KAABA_LON - longitude)
    val a = sin(dPhi / 2).pow(2) + cos(rad(latitude)) * cos(rad(KAABA_LAT)) * sin(dLambda / 2).pow(2)
    return 6371 * 2 * atan2(sqrt(a), sqrt(1 - a))
}

/** The turn from where the phone points to the Qibla, -180..180; positive is to the right. */
fun turnTo(target: Double, heading: Double): Double {
    val diff = normalise(target - heading)
    return if (diff > 180) diff - 360 else diff
}

